import 'package:dose_wise/src/features/dose_log/models/dose_record.dart';
import 'package:dose_wise/src/features/medications/models/medication.dart';
import 'package:dose_wise/src/features/stats/services/adherence_calculator.dart';

/// Builds a clean plain-text adherence summary suitable for the share
/// sheet (send to a caregiver or bring to an appointment). Pure Dart.
final class AdherenceReportBuilder {
  const AdherenceReportBuilder({
    this.calculator = const AdherenceCalculator(),
  });

  final AdherenceCalculator calculator;

  static const List<String> _months = [
    'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', //
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
  ];

  String build({
    required List<Medication> medications,
    required List<DoseRecord> records,
    required DateTime now,
    int days = 30,
  }) {
    final overall = calculator.period(
      medications: medications,
      records: records,
      now: now,
      days: days,
    );
    final perMedication = calculator.perMedication(
      medications: medications,
      records: records,
      now: now,
      days: days,
    );
    final streak = calculator.perfectDayStreak(
      medications: medications,
      records: records,
      now: now,
    );

    final start = DateTime(now.year, now.month, now.day - (days - 1));
    final buffer = StringBuffer()
      ..writeln('DoseWise — $days-day adherence report')
      ..writeln('${_date(start)} to ${_date(now)}')
      ..writeln()
      ..writeln('Overall: ${_percent(overall.rate)}'
          ' (${overall.taken} of ${overall.scheduled} doses taken)')
      ..writeln('Skipped: ${overall.skipped} · Missed: ${overall.missed}')
      ..writeln('Perfect-day streak: $streak ${streak == 1 ? 'day' : 'days'}');

    final lines = <String>[];
    for (final medication in medications) {
      final stats = perMedication[medication.id];
      if (stats == null || stats.scheduled == 0) continue;
      lines.add('- ${medication.name} (${medication.dosage}): '
          '${_percent(stats.rate)} — ${stats.taken}/${stats.scheduled} taken'
          '${stats.skipped > 0 ? ', ${stats.skipped} skipped' : ''}'
          '${stats.missed > 0 ? ', ${stats.missed} missed' : ''}');
    }
    if (lines.isNotEmpty) {
      buffer
        ..writeln()
        ..writeln('By medication:');
      lines.forEach(buffer.writeln);
    }

    buffer
      ..writeln()
      ..writeln('Generated by DoseWise on ${_date(now)}. '
          'Data stays on the device.');
    return buffer.toString();
  }

  static String _percent(double? rate) =>
      rate == null ? 'n/a' : '${(rate * 100).round()}%';

  static String _date(DateTime d) =>
      '${_months[d.month - 1]} ${d.day}, ${d.year}';
}
