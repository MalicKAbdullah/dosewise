import 'dart:typed_data';

import 'package:dose_wise/src/core/utils/formatters.dart';
import 'package:dose_wise/src/features/dose_log/models/dose_record.dart';
import 'package:dose_wise/src/features/medications/models/medication.dart';
import 'package:dose_wise/src/features/stats/services/adherence_calculator.dart';
import 'package:dose_wise/src/features/stats/services/pdf/pdf_fonts.dart';
import 'package:flutter/foundation.dart' show compute, immutable;
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

/// Everything needed to render one adherence report. Plain data only, so
/// it can be sent to a background isolate.
@immutable
final class AdherencePdfRequest {
  const AdherencePdfRequest({
    required this.medications,
    required this.records,
    required this.now,
    required this.days,
    required this.fonts,
    this.patientName,
  });

  final List<Medication> medications;
  final List<DoseRecord> records;
  final DateTime now;

  /// Report window length: 30 or 90 days ending today.
  final int days;
  final PdfFontBytes fonts;

  /// Shown under the title ("Patient: Amma"). Null hides the line.
  final String? patientName;
}

/// Renders the doctor-visit adherence report: overall + per-medication
/// adherence, a daily trend, and a dose log appendix, on A4 with the
/// Inter typeface embedded.
///
/// Layout is pure Dart (package:pdf) and unit-tested without platform
/// dependencies. From the UI, always call [renderInBackground].
abstract final class AdherenceReportPdfService {
  static const PdfColor _accent = PdfColor.fromInt(0xFF0D9488);
  static const PdfColor _muted = PdfColor.fromInt(0xFF64748B);
  static const PdfColor _faint = PdfColor.fromInt(0xFFE2E8F0);

  /// Builds the document synchronously. Exposed so tests can inspect the
  /// output; app code should prefer [renderInBackground].
  static pw.Document buildDocument(AdherencePdfRequest request) {
    const calculator = AdherenceCalculator();
    final now = request.now;
    final days = request.days;
    final rangeStart = DateTime(now.year, now.month, now.day - (days - 1));

    final overall = calculator.period(
      medications: request.medications,
      records: request.records,
      now: now,
      days: days,
    );
    final perMedication = calculator.perMedication(
      medications: request.medications,
      records: request.records,
      now: now,
      days: days,
    );
    final daily = calculator.daily(
      medications: request.medications,
      records: request.records,
      now: now,
      days: days,
    );

    final base = pw.Font.ttf(request.fonts.regular.buffer.asByteData());
    final semiBold = pw.Font.ttf(request.fonts.semiBold.buffer.asByteData());
    final bold = pw.Font.ttf(request.fonts.bold.buffer.asByteData());

    final doc = pw.Document(
      title: 'DoseWise medication report',
      producer: 'DoseWise',
      theme: pw.ThemeData.withFont(
        base: base,
        bold: bold,
        boldItalic: bold,
        italic: base,
      ),
    );

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.symmetric(horizontal: 42, vertical: 48),
        footer: (context) => pw.Container(
          alignment: pw.Alignment.centerRight,
          margin: const pw.EdgeInsets.only(top: 12),
          child: pw.Text(
            'Generated by DoseWise on ${_date(now)} — data stays on the '
            'device · Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 8, color: _muted),
          ),
        ),
        build: (_) => [
          _header(request, rangeStart, semiBold),
          pw.SizedBox(height: 18),
          _summaryRow(overall, semiBold),
          pw.SizedBox(height: 18),
          _sectionTitle('By medication', semiBold),
          _medicationTable(request, perMedication, semiBold),
          pw.SizedBox(height: 18),
          _sectionTitle('Daily adherence trend', semiBold),
          pw.SizedBox(height: 6),
          _trendChart(daily),
          pw.SizedBox(height: 18),
          _sectionTitle('Dose log appendix', semiBold),
          _doseLogTable(request, rangeStart, semiBold),
        ],
      ),
    );
    return doc;
  }

  /// Renders to bytes on the current isolate.
  static Future<Uint8List> render(AdherencePdfRequest request) =>
      buildDocument(request).save();

  /// Loads fonts (cached) and renders on a background isolate.
  static Future<Uint8List> renderInBackground({
    required List<Medication> medications,
    required List<DoseRecord> records,
    required DateTime now,
    required int days,
    String? patientName,
  }) async {
    final fonts = await PdfFontLoader.load();
    return compute(
      render,
      AdherencePdfRequest(
        medications: medications,
        records: records,
        now: now,
        days: days,
        fonts: fonts,
        patientName: patientName,
      ),
    );
  }

  static pw.Widget _header(
    AdherencePdfRequest request,
    DateTime rangeStart,
    pw.Font semiBold,
  ) {
    final patient = request.patientName;
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          'DoseWise — Medication report',
          style: pw.TextStyle(
            fontSize: 20,
            fontWeight: pw.FontWeight.bold,
            color: _accent,
          ),
        ),
        pw.SizedBox(height: 4),
        if (patient != null && patient.isNotEmpty)
          pw.Text(
            'Patient: $patient',
            style: pw.TextStyle(font: semiBold, fontSize: 11),
          ),
        pw.Text(
          '${request.days}-day report · ${_date(rangeStart)} to '
          '${_date(request.now)}',
          style: const pw.TextStyle(fontSize: 10, color: _muted),
        ),
        pw.Divider(color: _faint, height: 16),
      ],
    );
  }

  static pw.Widget _summaryRow(AdherenceStats overall, pw.Font semiBold) {
    pw.Widget cell(String value, String label) => pw.Expanded(
          child: pw.Container(
            padding: const pw.EdgeInsets.all(10),
            margin: const pw.EdgeInsets.only(right: 8),
            decoration: pw.BoxDecoration(
              border: pw.Border.all(color: _faint),
              borderRadius: pw.BorderRadius.circular(6),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  value,
                  style: pw.TextStyle(font: semiBold, fontSize: 16),
                ),
                pw.SizedBox(height: 2),
                pw.Text(
                  label,
                  style: const pw.TextStyle(fontSize: 8, color: _muted),
                ),
              ],
            ),
          ),
        );

    return pw.Row(
      children: [
        cell(_percent(overall.rate), 'Overall adherence'),
        cell('${overall.taken} of ${overall.scheduled}', 'Doses taken'),
        cell('${overall.skipped}', 'Skipped'),
        cell('${overall.missed}', 'Missed'),
      ],
    );
  }

  static pw.Widget _sectionTitle(String title, pw.Font semiBold) => pw.Text(
        title,
        style: pw.TextStyle(font: semiBold, fontSize: 13),
      );

  static pw.Widget _medicationTable(
    AdherencePdfRequest request,
    Map<String, AdherenceStats> perMedication,
    pw.Font semiBold,
  ) {
    final rows = <List<String>>[];
    for (final medication in request.medications) {
      final stats = perMedication[medication.id];
      if (stats == null || stats.scheduled == 0) continue;
      rows.add([
        medication.name,
        medication.dosage,
        describeSchedule(medication.schedule),
        _percent(stats.rate),
        '${stats.taken}',
        '${stats.skipped}',
        '${stats.missed}',
      ]);
    }
    if (rows.isEmpty) {
      return pw.Padding(
        padding: const pw.EdgeInsets.symmetric(vertical: 8),
        child: pw.Text(
          'No scheduled doses in this period.',
          style: const pw.TextStyle(fontSize: 9, color: _muted),
        ),
      );
    }
    return _table(
      headers: [
        'Medication',
        'Dosage',
        'Schedule',
        'Adherence',
        'Taken',
        'Skipped',
        'Missed',
      ],
      rows: rows,
      semiBold: semiBold,
    );
  }

  /// One thin bar per day; height follows the day's adherence rate. Days
  /// with nothing scheduled render as a faint stub.
  static pw.Widget _trendChart(List<DayAdherence> daily) {
    const chartHeight = 72.0;
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Container(
          height: chartHeight,
          decoration: const pw.BoxDecoration(
            border: pw.Border(bottom: pw.BorderSide(color: _muted)),
          ),
          child: pw.Row(
            crossAxisAlignment: pw.CrossAxisAlignment.end,
            children: [
              for (final day in daily)
                pw.Expanded(
                  child: pw.Container(
                    height: day.rate == null
                        ? 2.0
                        : (2.0 + (chartHeight - 4) * day.rate!),
                    margin: const pw.EdgeInsets.symmetric(horizontal: 0.6),
                    decoration: pw.BoxDecoration(
                      color: day.rate == null ? _faint : _accent,
                      borderRadius: const pw.BorderRadius.vertical(
                        top: pw.Radius.circular(1),
                      ),
                    ),
                  ),
                ),
            ],
          ),
        ),
        pw.SizedBox(height: 3),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              _date(daily.first.day),
              style: const pw.TextStyle(fontSize: 7, color: _muted),
            ),
            pw.Text(
              '100% = every scheduled dose taken',
              style: const pw.TextStyle(fontSize: 7, color: _muted),
            ),
            pw.Text(
              _date(daily.last.day),
              style: const pw.TextStyle(fontSize: 7, color: _muted),
            ),
          ],
        ),
      ],
    );
  }

  static pw.Widget _doseLogTable(
    AdherencePdfRequest request,
    DateTime rangeStart,
    pw.Font semiBold,
  ) {
    final medicationsById = {
      for (final m in request.medications) m.id: m,
    };
    final records = request.records
        .where(
          (r) =>
              !r.scheduledTime.isBefore(rangeStart) &&
              !r.scheduledTime.isAfter(request.now),
        )
        .toList()
      ..sort((a, b) => b.scheduledTime.compareTo(a.scheduledTime));

    if (records.isEmpty) {
      return pw.Padding(
        padding: const pw.EdgeInsets.symmetric(vertical: 8),
        child: pw.Text(
          'No logged doses in this period.',
          style: const pw.TextStyle(fontSize: 9, color: _muted),
        ),
      );
    }

    return _table(
      headers: ['Date', 'Time', 'Medication', 'Dosage', 'Status', 'Recorded'],
      rows: [
        for (final record in records)
          [
            _date(record.scheduledTime),
            formatTime(record.scheduledTime),
            medicationsById[record.medicationId]?.name ?? 'Unknown',
            medicationsById[record.medicationId]?.dosage ?? '—',
            record.outcome == DoseOutcome.taken ? 'Taken' : 'Skipped',
            formatTime(record.recordedAt),
          ],
      ],
      semiBold: semiBold,
    );
  }

  static pw.Widget _table({
    required List<String> headers,
    required List<List<String>> rows,
    required pw.Font semiBold,
  }) {
    return pw.TableHelper.fromTextArray(
      headers: headers,
      data: rows,
      border: null,
      headerStyle: pw.TextStyle(
        font: semiBold,
        fontSize: 8.5,
        color: PdfColors.white,
      ),
      headerDecoration: const pw.BoxDecoration(color: _accent),
      cellStyle: const pw.TextStyle(fontSize: 8.5),
      oddRowDecoration: const pw.BoxDecoration(
        color: PdfColor.fromInt(0xFFF1F5F9),
      ),
      cellPadding: const pw.EdgeInsets.symmetric(horizontal: 5, vertical: 3),
      cellAlignment: pw.Alignment.centerLeft,
      headerAlignment: pw.Alignment.centerLeft,
    );
  }

  static String _percent(double? rate) =>
      rate == null ? '—' : '${(rate * 100).round()}%';

  static String _date(DateTime d) => DateFormat('MMM d, yyyy').format(d);
}
